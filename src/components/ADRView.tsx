import React, { useState } from 'react';
import { MeetingMinutes } from '../types';
import { FileCode, Copy, Check, Download } from 'lucide-react';

interface ADRViewProps {
  minutes: MeetingMinutes;
}

export const ADRView: React.FC<ADRViewProps> = ({ minutes }) => {
  const [copiedId, setCopiedId] = useState<string | null>(null);

  const adrs = (minutes.decisions || []).map((dec, idx) => {
    const id = `ADR-${String(idx + 1).padStart(3, '0')}`;
    const title = dec.decision.length > 70 ? `${dec.decision.slice(0, 70)}...` : dec.decision;
    const context = `Discussed during '${minutes.title}'.\n\nExecutive Summary: ${minutes.executive_summary}`;
    const rationale = dec.rationale || 'Selected to uphold reliability, partition isolation, and low operational latency.';
    const alternatives = dec.discarded_options || [];

    const fullMarkdown = [
      `# ${id}: ${title}`,
      '',
      `**Status:** Accepted`,
      minutes.date ? `**Date:** ${minutes.date}` : '',
      '',
      '## Context and Problem Statement',
      context,
      '',
      '## Decision Outcome',
      `Chosen option: **${dec.decision}**`,
      '',
      '### Rationale & Positive Consequences',
      rationale,
      '',
      alternatives.length > 0 ? '## Considered Alternatives (Discarded)' : '',
      ...alternatives.map((a) => `- **${a}**: Rejected due to operational complexity or architectural misalignment.`),
      '',
      '<!-- Generated by ArchMoM Local Intelligence Engine -->'
    ].filter(Boolean).join('\n');

    return {
      id,
      title,
      context,
      decision: dec.decision,
      rationale,
      alternatives,
      markdown: fullMarkdown,
    };
  });

  const handleCopy = (id: string, text: string) => {
    navigator.clipboard.writeText(text);
    setCopiedId(id);
    setTimeout(() => setCopiedId(null), 2000);
  };

  const handleDownload = (id: string, text: string) => {
    const blob = new Blob([text], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${id.toLowerCase()}-decision.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-4 border-b border-slate-800">
        <div>
          <h1 className="text-xl font-bold text-white tracking-tight flex items-center gap-2">
            <FileCode className="w-5 h-5 text-indigo-400" />
            Architecture Decision Records (MADR Standard)
          </h1>
          <p className="text-xs text-slate-400 mt-1">
            Deterministic MADR documents generated directly from ratified decisions. Ready for your repository&apos;s <code className="text-indigo-300 font-mono">docs/adr/</code> directory.
          </p>
        </div>
        <div className="text-xs font-mono text-slate-400">
          {adrs.length} Records Compiled
        </div>
      </div>

      <div className="space-y-5">
        {adrs.map((adr) => (
          <div
            key={adr.id}
            className="bg-slate-900 border border-slate-800 rounded-lg p-5 space-y-4"
          >
            {/* Top metadata strip */}
            <div className="flex flex-wrap items-center justify-between gap-3 pb-3 border-b border-slate-800/80">
              <div className="flex items-center gap-2 text-xs">
                <span className="font-mono font-bold text-indigo-400">{adr.id}</span>
                <span className="text-slate-500">·</span>
                <span className="text-emerald-400 font-mono">Status: Accepted</span>
                <span className="text-slate-500">·</span>
                <span className="text-slate-400">{minutes.date || 'Current Sprint'}</span>
              </div>

              <div className="flex items-center gap-2">
                <button
                  onClick={() => handleCopy(adr.id, adr.markdown)}
                  className="flex items-center gap-1 py-1 px-2.5 bg-slate-800 hover:bg-slate-700 text-slate-300 rounded text-xs font-medium border border-slate-700 transition-colors"
                >
                  {copiedId === adr.id ? (
                    <>
                      <Check className="w-3.5 h-3.5 text-emerald-400" />
                      <span>Copied!</span>
                    </>
                  ) : (
                    <>
                      <Copy className="w-3.5 h-3.5" />
                      <span>Copy MADR</span>
                    </>
                  )}
                </button>
                <button
                  onClick={() => handleDownload(adr.id, adr.markdown)}
                  className="flex items-center gap-1 py-1 px-2.5 bg-slate-800 hover:bg-slate-700 text-slate-300 rounded text-xs font-medium border border-slate-700 transition-colors"
                >
                  <Download className="w-3.5 h-3.5" />
                  <span>Download .md</span>
                </button>
              </div>
            </div>

            {/* Content blocks */}
            <div>
              <h2 className="text-base font-bold text-white mb-2">{adr.title}</h2>
              <div className="text-xs text-slate-300 space-y-3">
                <div>
                  <h3 className="font-semibold text-slate-400 uppercase tracking-wider text-[11px] mb-1">
                    Context &amp; Problem Statement
                  </h3>
                  <p className="bg-slate-950 p-3 rounded border border-slate-800/60 leading-relaxed">
                    {adr.context}
                  </p>
                </div>

                <div>
                  <h3 className="font-semibold text-slate-400 uppercase tracking-wider text-[11px] mb-1">
                    Decision Outcome
                  </h3>
                  <p className="bg-slate-950 p-3 rounded border border-slate-800/60 font-medium text-slate-200 leading-relaxed">
                    Chosen Option: {adr.decision}
                  </p>
                </div>

                <div>
                  <h3 className="font-semibold text-slate-400 uppercase tracking-wider text-[11px] mb-1">
                    Rationale &amp; Consequences
                  </h3>
                  <p className="bg-slate-950 p-3 rounded border border-slate-800/60 text-slate-300 leading-relaxed">
                    {adr.rationale}
                  </p>
                </div>

                {adr.alternatives.length > 0 && (
                  <div>
                    <h3 className="font-semibold text-slate-400 uppercase tracking-wider text-[11px] mb-1">
                      Discarded Alternatives
                    </h3>
                    <ul className="bg-slate-950 p-3 rounded border border-slate-800/60 space-y-1">
                      {adr.alternatives.map((alt, i) => (
                        <li key={i} className="text-red-300/90 flex items-start gap-2">
                          <span className="text-red-400 font-mono">✕</span>
                          <span><strong>{alt}</strong> — rejected due to operational overhead or non-compliance with architectural invariants.</span>
                        </li>
                      ))}
                    </ul>
                  </div>
                )}
              </div>
            </div>
          </div>
        ))}

        {adrs.length === 0 && (
          <div className="p-8 text-center bg-slate-900 border border-slate-800 rounded-lg text-slate-400 text-xs">
            No architectural decisions to convert into ADRs yet. Ingest meeting notes or transcripts containing decisions.
          </div>
        )}
      </div>
    </div>
  );
};
